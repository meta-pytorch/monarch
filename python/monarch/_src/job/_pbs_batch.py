# pyre-strict

"""In-allocation runner for ``PBSJob`` batch mode.

Invoked as the body of the PBS script generated by ``apply(client_script=...)``,
or of a hand-written PBS script. Runs on the head node and:

  1. seeds a worker on every node of ``$PBS_NODEFILE`` with ``mpiexec``,
  2. runs the client with ``MONARCH_BATCH_JOB=1`` so its job reconnects to this
     allocation,
  3. terminates the workers in a ``finally``.

When this process exits the allocation is freed with the client's exit status.
"""

import argparse
import ipaddress
import os
import shlex
import subprocess
import sys
from typing import List, Optional

from monarch._src.job._batch_env import MONARCH_BATCH_JOB_ENV
from monarch._src.job.service_identity import (
    allocate_service_proc_ids,
    serialize_service_proc_ids,
    SERVICE_PROC_IDS_ENV,
)


def _worker_bootstrap(port: int, bind_to: Optional[str], rank_env: str) -> str:
    """Python source that starts one Monarch worker on this node.

    The worker advertises the node's short hostname, the form the client reads from
    qstat's ``exec_host`` and ``$PBS_NODEFILE``, so both sides name a node the same way
    even where ``gethostname()`` returns a fully qualified name. The launcher's
    PMI_/PALS_ variables are dropped after the rank is read: procs the worker spawns
    are not ranks of that launch.
    """
    address = f"tcp://{{socket.gethostname().split('.')[0]}}:{port}"
    if bind_to is not None:
        bind_ip = ipaddress.ip_address(bind_to)
        # A URL needs an IPv6 address in brackets; str(ip) has none.
        bind_host = f"[{bind_ip}]" if bind_ip.version == 6 else str(bind_ip)
        address += f"@tcp://{bind_host}:{port}"
    return f"""import os, socket
from monarch.actor import run_worker_loop_forever
from monarch._src.job.service_identity import service_proc_addr, ranked_service_proc_id_from_env
proc_id = ranked_service_proc_id_from_env(rank_env={rank_env!r})
for k in [k for k in os.environ if k.startswith(("PMI_", "PALS_"))]:
    os.environ.pop(k)
run_worker_loop_forever(address=service_proc_addr(f"{address}", proc_id), ca="trust_all_connections")
"""


def read_nodefile(path: Optional[str] = None) -> List[str]:
    """Short hostnames of the PBS allocation, in nodefile order, without duplicates."""
    path = path or os.environ.get("PBS_NODEFILE")
    if not path:
        raise RuntimeError("PBS_NODEFILE is not set: not inside a PBS allocation")
    if not os.path.isfile(path):
        raise RuntimeError(f"PBS_NODEFILE={path!r} is not a readable file")
    with open(path) as nodefile:
        names = [line.strip().split(".")[0] for line in nodefile if line.strip()]
    if not names:
        raise RuntimeError(f"PBS_NODEFILE={path!r} lists no hosts")
    # The nodefile repeats a host once per MPI slot; keep the first occurrence of each,
    # in file order (node 0 is the first host), not sorted.
    return list(dict.fromkeys(names))


def main(argv: Optional[List[str]] = None) -> None:
    parser = argparse.ArgumentParser(prog="monarch._src.job._pbs_batch")
    parser.add_argument("--port", type=int, default=22222)
    parser.add_argument("--bind-to")
    parser.add_argument("--mpiexec", default="mpiexec")
    parser.add_argument(
        "--mpiexec-arg",
        action="append",
        default=[],
        help="extra mpiexec flag, repeatable (e.g. --mpiexec-arg=--cpu-bind=none)",
    )
    parser.add_argument(
        "--rank-env",
        default="PMI_RANK",
        help="variable holding each worker's rank in the mpiexec launch",
    )
    parser.add_argument(
        "client",
        nargs="?",
        help="client command to run inside the allocation; omitted: workers only",
    )
    args = parser.parse_args(argv)

    hosts = read_nodefile()
    env = dict(os.environ)
    # A hand-written PBS script has no service ids yet; apply() exports them.
    if SERVICE_PROC_IDS_ENV not in env:
        env[SERVICE_PROC_IDS_ENV] = serialize_service_proc_ids(
            allocate_service_proc_ids(len(hosts))
        )
    # No warmup wait: the client's attach retries with backoff, so workers that
    # are still booting are handled by the channel layer, not a sleep here.
    workers = subprocess.Popen(
        [
            args.mpiexec,
            "-n",
            str(len(hosts)),
            "--ppn",
            "1",
            "--hosts",
            ",".join(hosts),
            *args.mpiexec_arg,
            sys.executable,
            "-c",
            _worker_bootstrap(args.port, args.bind_to, args.rank_env),
        ],
        env=env,
    )
    if args.client is None:
        sys.exit(workers.wait())
    try:
        client_env = dict(env, **{MONARCH_BATCH_JOB_ENV: "1"})
        returncode = subprocess.run(shlex.split(args.client), env=client_env).returncode
    finally:
        if workers.poll() is None:
            workers.terminate()
            try:
                workers.wait(timeout=30)
            except subprocess.TimeoutExpired:
                workers.kill()
    sys.exit(returncode)


if __name__ == "__main__":
    main()
